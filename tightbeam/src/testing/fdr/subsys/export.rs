//! The CSPM export for FDR4.
//!
//! It writes a CSP process in CSPM (machine-readable CSP), as a script for
//! the FDR4 model checker.
//!
//! # Sources
//!
//! - FDR 4.2.7 manual, CSPM syntax: <https://cocotec.io/fdr/manual/cspm/syntax.html>
//! - libcspm, the CSPM front end of FDR4, whose lexer states the identifier
//!   rule: <https://github.com/tomgr/libcspm/blob/master/src/CSPM/Parser/Lexer.x>

use core::fmt::{self, Display, Formatter};
use std::collections::HashSet;
use std::io::{self, Write};

use crate::testing::specs::composition::{CompositionError, ProcessExpr};
use crate::testing::specs::csp::{Action, Alphabet, Event, Process, State};
use crate::Errorizable;

/// The first line of every script.
const HEADER: &str = "-- Generated by tightbeam testing framework";

/// The CSPM export of a process, as a script for FDR4.
///
/// The script has these parts:
/// - A comment with the name of the process and its description.
/// - `datatype Events`, with one constructor per event, and the channels
///   `obs` and `hid` of type `Events` for the observable and hidden events.
/// - `datatype States`, with one constructor per state.
/// - One equation per state.
/// - The main process, which starts at the initial state and hides the channel
///   `hid` when the process has a hidden event.
///
/// A declaration that would be empty stays out of the script.
pub struct CspmExporter<'a> {
	/// The process that the script holds.
	process: &'a Process,
}

impl<'a> CspmExporter<'a> {
	/// Creates the export of `process`.
	pub fn new(process: &'a Process) -> Self {
		Self { process }
	}

	/// Writes the script of the process to `writer`.
	///
	/// The equation of a state is an external choice of `SKIP`, at an
	/// accepting state, and one prefix per action that the state enables. A
	/// prefix leads to the internal choice of every state that its event
	/// reaches, and a state with neither term is `STOP`. A timed transition
	/// is an edge whatever the clocks read, as [`Process::step`] reads it.
	///
	/// # Errors
	///
	/// - The error of `writer`.
	///
	/// # Examples
	///
	/// ```
	/// use tightbeam::testing::fdr::CspmExporter;
	/// use tightbeam::testing::specs::csp::{Event, Process, State};
	///
	/// let process = Process::builder("Ping")
	///     .initial_state(State("idle"))
	///     .add_observable(Event("ping"))
	///     .add_transition(State("idle"), Event("ping"), State("done"))
	///     .add_terminal(State("done"))
	///     .build()?;
	///
	/// let mut script = Vec::new();
	/// CspmExporter::new(&process).export(&mut script)?;
	///
	/// let script = String::from_utf8(script)?;
	/// assert!(script.contains("\nP_idle = obs.E_ping -> P_done\n"));
	/// assert!(script.ends_with("\nMain_Ping = P_idle\n"));
	/// # Ok::<(), Box<dyn core::error::Error>>(())
	/// ```
	pub fn export<W: Write>(&self, writer: &mut W) -> io::Result<()> {
		writeln!(writer, "{HEADER}")?;
		self.write_script(writer)
	}

	/// Writes the script of the process that `expr` evaluates to, as
	/// [`Self::export`] writes it, under a comment that names `expr`.
	///
	/// # Errors
	///
	/// - [`CspmExportError::Composition`] -- `expr` does not evaluate to a process.
	/// - [`CspmExportError::Io`] -- `writer` refuses the script.
	///
	/// # Examples
	///
	/// ```
	/// use tightbeam::testing::fdr::CspmExporter;
	/// use tightbeam::testing::specs::composition::{CompositionOperator, ProcessExpr};
	/// use tightbeam::testing::specs::csp::{Event, Process, State};
	///
	/// let ping = || {
	///     Process::builder("Ping")
	///         .initial_state(State("idle"))
	///         .add_observable(Event("ping"))
	///         .add_transition(State("idle"), Event("ping"), State("done"))
	///         .add_terminal(State("done"))
	///         .build()
	/// };
	///
	/// let left = Box::new(ProcessExpr::atomic("P", ping()?));
	/// let right = Box::new(ProcessExpr::atomic("Q", ping()?));
	/// let operator = CompositionOperator::Interleaved;
	/// let expression = ProcessExpr::Parallel { operator, left, right };
	///
	/// let mut script = Vec::new();
	/// CspmExporter::export_composition(&expression, &mut script)?;
	///
	/// let script = String::from_utf8(script)?;
	/// assert!(script.contains("\n-- Composition: (P ||| Q)\n"));
	/// # Ok::<(), Box<dyn core::error::Error>>(())
	/// ```
	pub fn export_composition<W: Write>(expr: &ProcessExpr, writer: &mut W) -> Result<(), CspmExportError> {
		let process = expr.evaluate()?;
		let name = expr.name();

		writeln!(writer, "{HEADER}")?;
		writeln!(writer, "{}", Comment { label: "Composition", text: &name })?;
		CspmExporter::new(&process).write_script(writer)?;
		Ok(())
	}

	/// Writes the script of the process after its header line.
	fn write_script<W: Write>(&self, writer: &mut W) -> io::Result<()> {
		let process = self.process;
		writeln!(writer, "{}", Comment { label: "Process", text: process.name })?;
		if let Some(description) = process.description {
			writeln!(writer, "{}", Comment { label: "Description", text: description })?;
		}
		writeln!(writer)?;

		self.write_events(writer)?;

		let states = sorted(&process.states);
		let constructors = Namespace::State.join(states.iter().map(|state| state.0), " | ");
		writeln!(writer, "-- States")?;
		writeln!(writer, "datatype States = {constructors}")?;
		writeln!(writer)?;

		writeln!(writer, "-- State equations")?;
		for state in &states {
			let name = Namespace::StateProcess.ident(state.0);
			let equation = self.equation(*state);
			writeln!(writer, "{name} = {equation}")?;
		}
		writeln!(writer)?;

		let main = Namespace::Process.ident(process.name);
		let initial = Namespace::StateProcess.ident(process.initial.0);
		writeln!(writer, "-- Main process")?;
		if process.hidden.is_empty() {
			writeln!(writer, "{main} = {initial}")
		} else {
			writeln!(writer, "{main} = {initial} \\ {{| hid |}}")
		}
	}

	/// Writes `datatype Events` and the channel of each alphabet that holds
	/// an event, when the process has an event.
	fn write_events<W: Write>(&self, writer: &mut W) -> io::Result<()> {
		let process = self.process;
		let events: HashSet<Event> = process.observable.union(&process.hidden).copied().collect();
		if events.is_empty() {
			return Ok(());
		}

		let names: Vec<&str> = sorted(&events).iter().map(|event| event.0).collect();
		let observable = (!process.observable.is_empty()).then_some(Alphabet::Observable);
		let hidden = (!process.hidden.is_empty()).then_some(Alphabet::Hidden);
		let channels: Vec<Alphabet> = observable.into_iter().chain(hidden).collect();
		let declarations = EventDeclarations { names, channels };

		writeln!(writer, "-- Events")?;
		writeln!(writer, "{declarations}")?;
		writeln!(writer)
	}

	/// The right side of the equation of `state`.
	fn equation(&self, state: State) -> String {
		let process = self.process;
		let termination = process.is_terminal(state).then(|| String::from("SKIP"));
		let prefixes = process.enabled(state).into_iter().map(|action| self.prefix(state, &action));
		let terms: Vec<String> = termination.into_iter().chain(prefixes).collect();
		if terms.is_empty() {
			return String::from("STOP");
		}

		terms.join(" [] ")
	}

	/// The prefix of `action` at `state`, which leads to the internal choice
	/// of every state that the event reaches.
	///
	/// [`Process::enabled`] lists an action whose event reaches a state, so
	/// the choice holds at least one state.
	fn prefix(&self, state: State, action: &Action) -> String {
		let channel = action.alphabet.cspm_channel();
		let event = Namespace::Event.ident(action.event.0);
		let mut targets = self.process.step(state, &action.event);
		targets.sort_unstable();
		targets.dedup();

		let choice = Namespace::StateProcess.join(targets.iter().map(|target| target.0), " |~| ");
		let successor = match targets.len() {
			1 => choice,
			_ => format!("({choice})"),
		};

		format!("{channel}.{event} -> {successor}")
	}
}

/// The refusal of [`CspmExporter::export_composition`].
///
/// # Examples
///
/// ```
/// use std::collections::HashSet;
///
/// use tightbeam::testing::fdr::{CspmExportError, CspmExporter};
/// use tightbeam::testing::specs::composition::{CompositionOperator, ProcessExpr};
/// use tightbeam::testing::specs::csp::{Event, Process, State};
///
/// let ping = || {
///     Process::builder("Ping")
///         .initial_state(State("idle"))
///         .add_observable(Event("ping"))
///         .add_transition(State("idle"), Event("ping"), State("done"))
///         .add_terminal(State("done"))
///         .build()
/// };
///
/// let left = Box::new(ProcessExpr::atomic("P", ping()?));
/// let right = Box::new(ProcessExpr::atomic("Q", ping()?));
/// let operator = CompositionOperator::Interface { events: HashSet::from([Event("pnig")]) };
/// let expression = ProcessExpr::Parallel { operator, left, right };
///
/// let refused = CspmExporter::export_composition(&expression, &mut Vec::new());
/// assert!(matches!(refused, Err(CspmExportError::Composition(_))));
/// # Ok::<(), Box<dyn core::error::Error>>(())
/// ```
#[derive(Debug, Errorizable)]
pub enum CspmExportError {
	/// The expression does not evaluate to a process.
	#[error("The expression does not evaluate to a process: {0}")]
	#[from]
	Composition(CompositionError),
	/// The writer refuses the script.
	#[error("The writer refuses the script: {0}")]
	#[from]
	Io(io::Error),
}

impl Alphabet {
	/// The CSPM channel that carries the events of this alphabet.
	fn cspm_channel(self) -> &'static str {
		match self {
			Self::Observable => "obs",
			Self::Hidden => "hid",
		}
	}
}

/// The namespace of a name in the script, which prefixes its identifier.
///
/// The prefixes differ from each other, so each namespace holds its own
/// identifiers. Each prefix holds an underscore, so a prefixed identifier
/// differs from each reserved word of CSPM and from each fixed name of the
/// script.
#[derive(Clone, Copy)]
enum Namespace {
	/// A constructor of `datatype Events`.
	Event,
	/// A constructor of `datatype States`.
	State,
	/// The equation of one state.
	StateProcess,
	/// The main process.
	Process,
}

impl Namespace {
	/// The identifier of `name` in this namespace.
	fn ident(self, name: &str) -> Ident<'_> {
		Ident { namespace: self, name }
	}

	/// The identifiers of `names` in this namespace, with `separator`
	/// between each two.
	fn join<'n>(self, names: impl IntoIterator<Item = &'n str>, separator: &str) -> String {
		let identifiers: Vec<String> = names.into_iter().map(|name| self.ident(name).to_string()).collect();
		identifiers.join(separator)
	}

	/// The prefix of each identifier in this namespace.
	fn prefix(self) -> &'static str {
		match self {
			Self::Event => "E_",
			Self::State => "S_",
			Self::StateProcess => "P_",
			Self::Process => "Main_",
		}
	}
}

/// A name of the process as a CSPM identifier in one namespace.
///
/// A CSPM identifier is a letter, then letters, digits, and underscores. The
/// identifier writes these parts in order:
/// - The prefix of the namespace.
/// - Each ASCII letter and digit of the name, as it is.
/// - Each other character of the name as `_`, its code point in hexadecimal, and `_`.
///
/// An underscore of the name is `_5f_`, so each underscore after the prefix
/// marks an escape, and each name has its own identifier.
struct Ident<'a> {
	/// The namespace of the name.
	namespace: Namespace,
	/// The name, as the process holds it.
	name: &'a str,
}

impl Display for Ident<'_> {
	fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
		f.write_str(self.namespace.prefix())?;
		for character in self.name.chars() {
			if character.is_ascii_alphanumeric() {
				write!(f, "{character}")?;
			} else {
				write!(f, "_{:x}_", u32::from(character))?;
			}
		}

		Ok(())
	}
}

/// A comment of the script, with one comment line per line of its text.
///
/// A CSPM comment runs from `--` to the end of its line, so a line of the
/// text starts a comment of its own.
struct Comment<'a> {
	/// The label of the first line.
	label: &'a str,
	/// The text, as the process holds it.
	text: &'a str,
}

impl Display for Comment<'_> {
	fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
		let mut lines = self.text.lines();
		let first = lines.next().unwrap_or_default();
		write!(f, "-- {}: {first}", self.label)?;
		for line in lines {
			write!(f, "\n-- {line}")?;
		}

		Ok(())
	}
}

/// The CSPM script of the observable events of a run, as the sequence
/// `Trace`, with the declarations of its events.
pub(crate) struct TraceScript<'a> {
	/// The label of each observable event, in the order of the run.
	labels: &'a [String],
}

impl<'a> TraceScript<'a> {
	/// Creates the script of `labels`, in the order of the run.
	pub(crate) fn new(labels: &'a [String]) -> Self {
		Self { labels }
	}

	/// Writes the script to `writer`.
	///
	/// A run with an event declares `datatype Events` and `channel obs`, and
	/// each member of `Trace` is the event on `obs`.
	pub(crate) fn write<W: Write>(&self, writer: &mut W) -> io::Result<()> {
		let mut names: Vec<&str> = self.labels.iter().map(String::as_str).collect();
		names.sort_unstable();
		names.dedup();
		let member = |label: &String| format!("obs.{}", Namespace::Event.ident(label));
		let members: Vec<String> = self.labels.iter().map(member).collect();

		writeln!(writer, "-- Execution trace")?;
		if !names.is_empty() {
			let declarations = EventDeclarations { names, channels: vec![Alphabet::Observable] };
			writeln!(writer, "{declarations}")?;
		}
		writeln!(writer, "Trace = <{}>", members.join(", "))
	}
}

/// The declarations of the events of a script: `datatype Events`, with one
/// constructor per event, and the channel of each alphabet, of type `Events`.
struct EventDeclarations<'a> {
	/// The names of the events, sorted, each once.
	names: Vec<&'a str>,
	/// The alphabets whose channels the script declares.
	channels: Vec<Alphabet>,
}

impl Display for EventDeclarations<'_> {
	fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
		let constructors = Namespace::Event.join(self.names.iter().copied(), " | ");
		write!(f, "datatype Events = {constructors}")?;
		for alphabet in &self.channels {
			write!(f, "\nchannel {} : Events", alphabet.cspm_channel())?;
		}

		Ok(())
	}
}

/// The members of `set` in their order, so two exports of one process write
/// one script.
fn sorted<T: Copy + Ord>(set: &HashSet<T>) -> Vec<T> {
	let mut members: Vec<T> = set.iter().copied().collect();
	members.sort_unstable();
	members
}

