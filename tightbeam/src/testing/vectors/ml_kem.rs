//! One vector of each ML-KEM operation for the parameter sets the house runs,
//! from the NIST ACVP for FIPS 203: the `internalProjection` files of
//! ACVP-Server at commit `65370b8`, `ML-KEM-keyGen-FIPS203` and
//! `ML-KEM-encapDecap-FIPS203`.
//!
//! # Sources
//!
//! - FIPS 203 (August 2024), §6, the internal algorithms the vectors drive, and §6.3, the implicit rejection.
//! - ACVP-Server, `gen-val/json-files`:
//!   <https://github.com/usnistgov/ACVP-Server/tree/65370b8/gen-val/json-files>

/// The vectors of one parameter set, each value in hex.
pub struct MlKemVectors {
	/// Key generation: the seed `d`.
	pub keygen_d: &'static str,
	/// Key generation: the seed `z`.
	pub keygen_z: &'static str,
	/// Key generation: the encapsulation key of `d` and `z`.
	pub keygen_ek: &'static str,
	/// Key generation: the decapsulation key of `d` and `z`.
	pub keygen_dk: &'static str,
	/// Encapsulation: the encapsulation key.
	pub encap_ek: &'static str,
	/// Encapsulation: the message `m` it draws.
	pub encap_m: &'static str,
	/// Encapsulation: the ciphertext.
	pub encap_c: &'static str,
	/// Encapsulation: the shared key.
	pub encap_k: &'static str,
	/// Decapsulation: the decapsulation key of the test group.
	pub decap_dk: &'static str,
	/// Decapsulation: a ciphertext as encapsulation produced it.
	pub decap_c: &'static str,
	/// Decapsulation: the shared key of [`Self::decap_c`].
	pub decap_k: &'static str,
	/// Decapsulation: a modified ciphertext.
	pub reject_c: &'static str,
	/// Decapsulation: the implicit rejection key of [`Self::reject_c`]
	/// (FIPS 203 §6.3).
	pub reject_k: &'static str,
}

